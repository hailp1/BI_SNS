        function t(key) {



            const lang = (typeof state !== 'undefined' && state && state.currentLang) ? state.currentLang : (localStorage.getItem('cj_lang') || 'vi');



            if (I18N[lang] && I18N[lang][key] !== undefined) {



                return I18N[lang][key];



            }



            if (I18N['vi'] && I18N['vi'][key] !== undefined) {



                return I18N['vi'][key];



            }



            return key;



        }







        function setLanguage(lang) {



            if (!['vi', 'en', 'ko'].includes(lang)) lang = 'vi';



            if (typeof state !== 'undefined' && state) {



                state.currentLang = lang;



            }



            try {



                localStorage.setItem('cj_lang', lang);



            } catch(e) {}







            // 1. Update Desktop buttons



            ['vi', 'en', 'ko'].forEach(l => {



                const btn = document.getElementById('lang-btn-' + l);



                if (btn) {



                    if (l === lang) {



                        btn.className = 'px-2 py-1 rounded text-xs font-black transition-all flex items-center gap-1.5 bg-white text-blue-900 shadow';



                    } else {



                        btn.className = 'px-2 py-1 rounded text-xs font-black transition-all flex items-center gap-1.5 text-white hover:bg-white/20';



                    }



                }



            });







            // 1b. Update Mobile Drawer buttons



            ['vi', 'en', 'ko'].forEach(l => {



                const mBtn = document.getElementById('m-lang-btn-' + l);



                if (mBtn) {



                    if (l === lang) {



                        mBtn.className = 'py-2 px-1 rounded-xl text-xs font-black border flex flex-col items-center gap-1 transition-all bg-sky-50 text-sky-800 border-sky-300 shadow-sm';



                    } else {



                        mBtn.className = 'py-2 px-1 rounded-xl text-xs font-black border flex flex-col items-center gap-1 transition-all bg-white text-slate-700 border-slate-200';



                    }



                }



            });







            // 2. Update DOM elements with data-i18n, data-i18n-title, data-i18n-placeholder



            document.querySelectorAll('[data-i18n]').forEach(el => {



                const k = el.getAttribute('data-i18n');



                if (k) {



                    const translated = t(k);



                    if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {



                        el.placeholder = translated;



                    } else {



                        el.innerHTML = translated;



                    }



                }



            });



            document.querySelectorAll('[data-i18n-title]').forEach(el => {



                const k = el.getAttribute('data-i18n-title');



                if (k) el.title = t(k);



            });



            document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {



                const k = el.getAttribute('data-i18n-placeholder');



                if (k) el.placeholder = t(k);



            });







            // 3. Update titles & breadcrumbs



            updateHeaderTitles();



            updateGtTreeSubMenuUI();







            // 3b. Update User Profile Box



            if (typeof applyUserToUI === 'function') {



                let savedUserJson = localStorage.getItem('cj_current_user') || sessionStorage.getItem('cj_current_user');



                if (savedUserJson) {



                    try {



                        applyUserToUI(JSON.parse(savedUserJson));



                    } catch(e) {}



                }



            }







            // 3c. Update Static Selects



            updateYearDropdown();



            populateDashChannel();



            populateRepChannel();







            // 4. Update dropdowns default labels
            if (window._appBooted && typeof initDropdowns === 'function') {
                initDropdowns();
            }

            // 5. Update month selector UI
            if (typeof updateMonthChipsUI === 'function') {
                updateMonthChipsUI();
            }

            // 6. Update period status note
            if (typeof updatePeriodNote === 'function') {
                updatePeriodNote();
            }

            // 7. Re-render active tab (charts + tree tables)
            if (window._appBooted && typeof renderActiveTab === 'function') {
                renderActiveTab();
            }
        }

